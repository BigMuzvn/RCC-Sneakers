export type League = 'La Liga' | 'Ligue 1' | 'Premier League' | 'Bundesliga' | 'Serie A' | 'Sélections';

export type JerseyVariant = {
  size: 'S' | 'M' | 'L' | 'XL' | 'XXL';
  stock: number;
};

/** Same shape convention as Product: snake_case on the fields the PHP API will return. */
export type Jersey = {
  id: number;
  slug: string;
  club: string;
  league: League;
  brand: string;
  kit: 'Domicile' | 'Extérieur' | 'Third';
  season: string;
  colorway: string;
  price_xof: number;
  old_price_xof: number | null;
  is_new_drop: boolean;
  image: string | null;
  accent: string;
  variants: JerseyVariant[];
};

const sizes = (stock: number[]): JerseyVariant[] =>
  (['S', 'M', 'L', 'XL', 'XXL'] as const).map((size, index) => ({ size, stock: stock[index] ?? 0 }));

